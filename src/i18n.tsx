const DICTS: Record<Lang, Dict> = { en, it };

function lookup(dict: Dict, key: string): string | undefined {
  let cur: string | Dict | undefined = dict;
  for (const part of key.split(".")) {
    if (cur === undefined || typeof cur === "string") return undefined;
    cur = cur[part];
  }
  return typeof cur === "string" ? cur : undefined;
}

export type Params = Record<string, string | number>;
export type T = (key: string, params?: Params) => string;

function interpolate(s: string, params?: Params) {
  if (!params) return s;
  return s.replace(/\{(\w+)\}/g, (m, k) => (k in params ? String(params[k]) : m));
}

function savedLang(): Lang | null {
  const saved = storageGet("lang");
  return saved === "it" || saved === "en" ? saved : null;
}

function fromLocale(locale: string | null | undefined): Lang {
  return locale?.toLowerCase().startsWith("it") ? "it" : "en";
}

function detect(): Lang {
  return savedLang() ?? fromLocale(typeof navigator !== "undefined" ? navigator.language : null);
}

const Ctx = createContext<{ lang: Lang; setLang: (l: Lang) => void; t: T } | null>(null);

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>(detect);
  const setLang = useCallback((l: Lang) => {
    setLangState(l);
    storageSet("lang", l);
    document.documentElement.lang = l;
  }, []);
  const t = useCallback<T>(
    (key, params) => interpolate(lookup(DICTS[lang], key) ?? lookup(DICTS.en, key) ?? key, params),
    [lang],
  );
  // Until the user picks a language, follow the OS setting.
  useEffect(() => {
    if (savedLang()) return;
    invoke<string | null>("system_locale")
      .then((l) => {
        const next = fromLocale(l);
        setLangState(next);
        document.documentElement.lang = next;
      })
      .catch(() => {});
  }, []);
  const value = useMemo(() => ({ lang, setLang, t }), [lang, setLang, t]);
  return <Ctx.Provider value={value}>{children}</Ctx.Provider>;
}

export function useI18n() {
  const v = useContext(Ctx);
  if (!v) throw new Error("useI18n outside I18nProvider");
  return v;
}

/** Has a translation for this key (used for optional value labels). */
export function useHas() {
  const { lang } = useI18n();
  return (key: string) => lookup(DICTS[lang], key) !== undefined;
}
